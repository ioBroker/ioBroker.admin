/**
 * Readable text of an error thrown by axios: the response body if the server answered, else message or code
 *
 * @param e the caught error
 */
function getRequestErrorText(e: unknown): string {
    const error = e as { response?: { data?: unknown }; message?: string; code?: string };
    return error.response ? String(error.response.data) : `${error.message || error.code}`;
}

